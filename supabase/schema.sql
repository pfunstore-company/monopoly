-- 遊戲資料表 (Sky 2026-10-23): in the private schema "game", which Supabase's public Data API does not offer to
-- anyone; only the Edge Function "api" (connecting as the database owner) reads and writes them. Row Level
-- Security is on for every table as a second lock. Safe to run again.
create schema if not exists game;
revoke all on schema game from public, anon, authenticated;

-- Sky ticked "Automatically expose new tables" when making the project: undo that for tables made later in public.
alter default privileges for role postgres in schema public revoke all on tables from anon, authenticated;

create table if not exists game.users (
  id bigint generated by default as identity primary key,
  name text not null,
  name_key text not null unique,
  salt text not null,
  hash text not null,
  created bigint not null,
  fails integer not null default 0,
  locked_until bigint not null default 0
);
create table if not exists game.sessions (token_hash text primary key, user_id bigint not null, created bigint not null);
create index if not exists sessions_user on game.sessions (user_id);
create table if not exists game.saves (user_id bigint primary key, data text not null, updated bigint not null);
create table if not exists game.links (uid text primary key, provider text not null, user_id bigint not null, created bigint not null);
create index if not exists links_user on game.links (user_id);
create table if not exists game.ad_claims (
  nonce text primary key, user_id bigint not null, kind text not null, day text not null,
  created bigint not null, status text not null, txn text
);
create index if not exists ad_claims_user_day on game.ad_claims (user_id, day);
create table if not exists game.ssv_txns (txn text primary key, created bigint not null);
create table if not exists game.grants (
  id bigint generated by default as identity primary key, user_id bigint not null, kind text not null,
  energy bigint not null, created bigint not null
);
create index if not exists grants_user on game.grants (user_id, created);
create table if not exists game.save_flags (
  id bigint generated by default as identity primary key, user_id bigint not null, created bigint not null, detail text not null
);

alter table game.users enable row level security;
alter table game.sessions enable row level security;
alter table game.saves enable row level security;
alter table game.links enable row level security;
alter table game.ad_claims enable row level security;
alter table game.ssv_txns enable row level security;
alter table game.grants enable row level security;
alter table game.save_flags enable row level security;
revoke all on all tables in schema game from public, anon, authenticated;
